; #############################################################################
; #                                   get_cr3                                 #
; #############################################################################
;
; return:
;       cr3 (8 byte)
;
global get_cr3
get_cr3:
    mov rax, cr3
    ret

; #############################################################################
; #                                   set_cr3                                 #
; #############################################################################
;
; arg:
;       1: cr3 (8 byte)
;
global set_cr3
set_cr3:
    mov cr3, rdi
    ret
