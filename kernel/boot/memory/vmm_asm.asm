section .bootstrap
; #############################################################################
; #                         bootstrap_get_cr3                                 #
; #############################################################################
;
; return:
;       cr3 (8 byte)
;
global bootstrap_get_cr3
bootstrap_get_cr3:
    mov rax, cr3
    ret

; #############################################################################
; #                            bootstrap_set_cr3                              #
; #############################################################################
;
; arg:
;       1: cr3 (8 byte)
;
global bootstrap_set_cr3
bootstrap_set_cr3:
    mov cr3, rdi
    ret
